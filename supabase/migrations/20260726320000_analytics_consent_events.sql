-- Consent-gated, first-party product analytics.
-- Collection is off until the user explicitly enables it. Raw events are
-- intentionally short-lived and cannot contain large payloads.

create table public.analytics_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  product_analytics_enabled boolean not null default false,
  sale_sharing_opt_out boolean not null default true
    check (sale_sharing_opt_out = true),
  consent_version text not null default '2026-07-25',
  prompted_at timestamptz,
  consented_at timestamptz,
  updated_at timestamptz not null default now()
);

create trigger analytics_preferences_updated
before update on public.analytics_preferences
for each row execute function public.set_updated_at();

create table public.analytics_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_name text not null check (
    event_name in (
      'app_open',
      'screen_view',
      'camera_open',
      'dual_mode_started',
      'photo_captured',
      'photo_saved',
      'daily_post_published',
      'story_published',
      'map_open',
      'workout_started',
      'workout_completed',
      'paywall_viewed',
      'purchase_started',
      'purchase_completed'
    )
  ),
  properties jsonb not null default '{}'::jsonb check (
    jsonb_typeof(properties) = 'object'
    and octet_length(properties::text) <= 2048
  ),
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index analytics_events_user_time_idx
  on public.analytics_events (user_id, occurred_at desc);
create index analytics_events_name_time_idx
  on public.analytics_events (event_name, occurred_at desc);

alter table public.analytics_preferences enable row level security;
alter table public.analytics_events enable row level security;

revoke all on table public.analytics_preferences from anon;
revoke all on table public.analytics_events from anon;
revoke all on sequence public.analytics_events_id_seq from anon;

grant select, insert, update, delete on table public.analytics_preferences to authenticated;
grant select, insert, delete on table public.analytics_events to authenticated;
grant usage, select on sequence public.analytics_events_id_seq to authenticated;

create policy "analytics preferences select own"
on public.analytics_preferences for select to authenticated
using ((select auth.uid()) = user_id);

create policy "analytics preferences insert own"
on public.analytics_preferences for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "analytics preferences update own"
on public.analytics_preferences for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "analytics preferences delete own"
on public.analytics_preferences for delete to authenticated
using ((select auth.uid()) = user_id);

create policy "analytics events select own"
on public.analytics_events for select to authenticated
using ((select auth.uid()) = user_id);

create policy "analytics events insert own when enabled"
on public.analytics_events for insert to authenticated
with check (
  (select auth.uid()) = user_id
  and exists (
    select 1
    from public.analytics_preferences preference
    where preference.user_id = (select auth.uid())
      and preference.product_analytics_enabled
  )
);

create policy "analytics events delete own"
on public.analytics_events for delete to authenticated
using ((select auth.uid()) = user_id);

-- Raw interaction events are deliberately transient. Product decisions should
-- use aggregate reports, not indefinite user-level histories.
select cron.schedule(
  'analytics-events-retention',
  '17 4 * * *',
  $$delete from public.analytics_events where created_at < now() - interval '90 days'$$
);
